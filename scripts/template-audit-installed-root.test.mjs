import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { spawnSync } from 'node:child_process';
const source = readFileSync(resolve(import.meta.dirname, '../.agents/procedures/template-audit/SKILL.md'), 'utf8');
const binding = source.match(/<!-- template-audit:bind -->\s*```bash\n([\s\S]*?)\n```/);
test('rendered-document inputs keep invocation cwd while checks bind nearest installed project', t => {
  assert.ok(binding, 'canonical executable binding must replace enclosing Git-root instruction');
  const outer=realpathSync(mkdtempSync(join(tmpdir(),'template outer git ')));
  t.after(()=>rmSync(outer,{recursive:true,force:true}));
  assert.equal(spawnSync('git',['init','-q'],{cwd:outer}).status,0);
  const project=join(outer,'installed project with spaces');
  const procedure=join(project,'.agents/procedures/template-audit');
  const nested=join(project,'nested cwd with spaces');
  mkdirSync(procedure,{recursive:true});mkdirSync(nested,{recursive:true});
  writeFileSync(join(procedure,'SKILL.md'),'installed fixture marker\n');
  mkdirSync(join(project,'scripts')); writeFileSync(join(project,'scripts/check-delivered.sh'),'printf "consumer-check\\n"\n');
  mkdirSync(join(outer,'scripts'));writeFileSync(join(outer,'scripts/check-delivered.sh'),'printf "WRONG-outer-check\\n"\n');
  const relative='supplied doc with spaces.md', absolute=join(outer,'absolute supplied.md');
  writeFileSync(join(nested,relative),'rendered target\n');writeFileSync(absolute,'absolute target\n');
  const env={...process.env};for(const key of ['GIT_DIR','GIT_WORK_TREE','GIT_COMMON_DIR'])delete env[key];
  assert.equal(spawnSync('git',['rev-parse','--show-toplevel'],{cwd:nested,env,encoding:'utf8'}).stdout.trim(),outer,'adverse fixture genuinely has different enclosing Git root');
  const inspect='\nprintf "root=%s\\n" "$PWD"; printf "input=%s\\n" "${rendered_documents[@]}"; bash scripts/check-delivered.sh';
  const r=spawnSync('bash',['-c',binding[1]+inspect,'template-audit',relative,absolute],{cwd:nested,env,encoding:'utf8'});
  assert.equal(r.status,0,r.stderr);assert.equal(r.stdout,`root=${project}\ninput=${join(nested,relative)}\ninput=${absolute}\nconsumer-check\n`);
  const missing=spawnSync('bash',['-c',binding[1]+inspect,'template-audit',absolute],{cwd:outer,env,encoding:'utf8'});
  assert.equal(missing.status,2);assert.match(missing.stderr,/missing installed-project prerequisite/);assert.equal(missing.stdout,'');
});
