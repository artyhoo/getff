#!/usr/bin/env node
/**
 * render-terms-style — docs/site/terms.md region (a) → the Vale substitution rule (S0q).
 *
 * D-Q7: only glossary entries marked `Do not use (name):` render into the Vale
 * substitution (level error); a plain `Do not use:` list stays JUDGE material.
 * The renderer is the seam between the hand-written region (a) of
 * docs/site/terms.md and the GENERATED styles/getff/Names.yml that the
 * docs/site-quality/vale/.vale.ini profile loads as package `getff`.
 *
 * Region (a) entry grammar (both readable and machine-parsed):
 *
 *   ### <canonical term>
 *   <one-sentence definition…>
 *   Do not use (name): <forbidden form>[, <forbidden form>…] — <why>
 *
 * Each forbidden form becomes a `swap:` key mapping to the canonical term.
 * Acronym-like forms (all-caps, ≤4 chars) are emitted with word-boundary
 * lookarounds — the D-Q7 «CC (word-bounded)» entry, measured against Vale
 * 3.21.0: `CC` fires, `ACCB` does not. All other keys are emitted as quoted
 * literals (Vale phrase-matches them).
 *
 * Usage:
 *   node scripts/render-terms-style.mjs --write   regenerate Names.yml
 *   node scripts/render-terms-style.mjs --check   exit 1 naming drift
 *   --root <dir>                                  operate on a fixture root
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolveRoot();
const TERMS = 'docs/site/terms.md';
const NAMES = 'docs/site-quality/vale/styles/getff/Names.yml';

function resolveRoot() {
  const rootIdx = process.argv.indexOf('--root');
  if (rootIdx !== -1 && process.argv[rootIdx + 1]) return resolve(process.argv[rootIdx + 1]);
  return join(here, '..');
}

/** Pull `Do not use (name):` entries out of region (a) of terms.md. */
export function parseNameEntries(source) {
  const entries = [];
  let current = null;
  for (const rawLine of source.split('\n')) {
    const heading = /^###\s+(.+?)\s*$/.exec(rawLine);
    if (heading) {
      current = { term: heading[1], forbidden: [] };
      entries.push(current);
      continue;
    }
    const ban = /^Do not use \(name\):\s*(.+?)\s*$/.exec(rawLine);
    if (ban && current) {
      // `<form>, <form> — <why>`: everything before the first em dash is the
      // forbidden-form list; the reason is human documentation, not machine input.
      const forms = ban[1].split(/\s+—\s+/)[0];
      for (const form of forms.split(',')) {
        const trimmed = form.trim();
        if (trimmed) current.forbidden.push(trimmed);
      }
    }
    // Any other `## ` heading outside an entry resets it — region (b) or prose
    // after the entries must not absorb a later entry's forms.
    if (/^##\s+/.test(rawLine) && !/^###/.test(rawLine)) current = null;
  }
  return entries.filter((e) => e.forbidden.length > 0);
}

/** Word-bound the acronym-like forms; quote everything. */
export function swapKey(form) {
  if (/^[A-Z0-9]{1,4}$/.test(form)) {
    return `(?<![A-Za-z0-9-])${form}(?![A-Za-z0-9-])`;
  }
  return form;
}

function yamlQuote(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

export function renderNamesYml(entries) {
  const swaps = [];
  for (const entry of entries) {
    for (const form of entry.forbidden) {
      swaps.push(`  ${yamlQuote(swapKey(form))}: ${yamlQuote(entry.term)}`);
    }
  }
  swaps.sort(); // deterministic order — identical inputs produce byte-identical output
  return [
    '# GENERATED by scripts/render-terms-style.mjs — do not hand-edit.',
    '# Source: docs/site/terms.md region (a) — the `Do not use (name):` entries (D-Q7).',
    '# Regenerate: node scripts/render-terms-style.mjs --write',
    'extends: substitution',
    "message: Use '%s' instead of '%s'.",
    'level: error',
    'ignorecase: false',
    'swap:',
    ...swaps,
    '',
  ].join('\n');
}

function main() {
  const mode = process.argv.includes('--check') ? 'check' : 'write';
  const termsPath = join(repoRoot, TERMS);
  const namesPath = join(repoRoot, NAMES);
  const source = readFileSync(termsPath, 'utf8');
  const entries = parseNameEntries(source);
  if (entries.length === 0) {
    console.error(`✗ ${TERMS} carries no \`Do not use (name):\` entries — nothing to render`);
    process.exit(1);
  }
  const rendered = renderNamesYml(entries);

  let existing = null;
  try {
    existing = readFileSync(namesPath, 'utf8');
  } catch {
    existing = null;
  }

  if (mode === 'check') {
    if (existing === null) {
      console.error(`✗ ${NAMES} is missing; Fix: node scripts/render-terms-style.mjs --write`);
      process.exit(1);
    }
    if (existing !== rendered) {
      console.error(`✗ ${NAMES} drifted from ${TERMS} region (a)`);
      console.error('  Fix: node scripts/render-terms-style.mjs --write');
      process.exit(1);
    }
    console.log(`✓ ${NAMES} matches ${TERMS} region (a) (${entries.length} entries)`);
    return;
  }

  mkdirSync(dirname(namesPath), { recursive: true });
  writeFileSync(namesPath, rendered);
  console.log(`✓ wrote ${NAMES} (${entries.length} entries)`);
}

// Only run main when executed directly — the test harness imports the pure parts.
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isMain) main();
